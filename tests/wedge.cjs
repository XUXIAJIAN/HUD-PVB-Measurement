const assert=require('node:assert/strict'),fs=require('fs');
const P=require('../core.js');
const bytes=Buffer.from(fs.readFileSync(require('node:path').join(__dirname,'../edit-sample.js'),'utf8').match(/'([^']+)'/)[1],'base64');
const data=P.csv(bytes.toString()),template=P.csvTemplate(bytes);
assert.equal(data.length,1001);assert.deepEqual(Buffer.from(P.exportTemplate(template,data)),bytes);
const r=P.adjustWedge(data,300,600,0.4,'target',60,1);
assert.ok(Math.abs(r.after-.4)<1e-12);
assert.deepEqual(r.data.filter(p=>p[0]<=300),data.filter(p=>p[0]<=300));
for(let i=600;i<data.length;i++)assert.ok(Math.abs(r.data[i][1]-data[i][1]-r.offset)<1e-12);
const exported=Buffer.from(P.exportTemplate(template,r.data));
assert.equal(exported.toString().split('[Data]')[0],bytes.toString().split('[Data]')[0]);
assert.equal(exported.toString().split('\r\n').length,bytes.toString().split('\r\n').length);
const again=P.csv(exported.toString());assert.deepEqual(again.map(p=>p[0]),data.map(p=>p[0]));
assert.ok(Math.max(...again.map((p,i)=>Math.abs(p[1]-r.data[i][1])))<=.00005000001);
assert.throws(()=>P.adjustWedge(data,600,300,.1,'delta'));assert.throws(()=>P.adjustWedge(data,-1,300,.1,'delta'));
assert.throws(()=>P.adjustWedge(data,0,1000,-10,'delta'));
const irregular=[[0,.5],[35,.51],[80,.53],[140,.56],[230,.59],[400,.63]];
assert.ok(Math.abs(P.adjustWedge(irregular,35,230,.3,'target',40,1).after-.3)<1e-12);
console.log('PASS numerical target, boundary continuity, validation, nonuniform samples, byte-identical unchanged export, original headers/positions/line endings and precision.');
